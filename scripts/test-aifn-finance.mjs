import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { analyzeFinance, metricsAt, auditAt, auc, splitRecords, fitLogistic, fitRegression, kmeans, CLASS_FEATURES, REG_FEATURES } from '../src/scripts/aifn-finance-engine.js';

const records = JSON.parse(await readFile('public/aifn/data/credit.json', 'utf8')).records;
const start = performance.now();
const result = analyzeFinance(records);
const runtimeMs = performance.now() - start;
assert.deepEqual(result.summary, { count: 1000, good: 700, bad: 300, missing: 0 });
assert.equal(result.split.trainCount, 800);
assert.equal(result.split.testCount, 200);
assert.deepEqual(analyzeFinance(records), result, 'identical input + seed must reproduce all outputs');
assert.notDeepEqual(analyzeFinance(records, { seed: 42 }).split.testRows, result.split.testRows);
assert.equal(new Set([...result.split.trainRows, ...result.split.testRows]).size, 1000);
const { train, test } = splitRecords(records);
assert.equal(train.filter(r => r.risk).length, 240);
assert.equal(test.filter(r => r.risk).length, 60);
assert.deepEqual(CLASS_FEATURES, ['duration', 'log1p(amount)', 'installmentRate', 'existingCredits']);
assert.deepEqual(REG_FEATURES, ['duration', 'installmentRate', 'existingCredits']);
const scores = result.classification.scores;
const noPositive = metricsAt(scores, 1);
assert.equal(noPositive.precision, null);
assert.equal(noPositive.TP, 0);
assert.equal(noPositive.FN, 60);
const allPositive = metricsAt(scores, 0);
assert.equal(allPositive.TP, 60);
assert.equal(allPositive.FP, 140);
assert.equal(allPositive.recall, 1);
assert.equal(allPositive.fpr, 1);
assert.deepEqual(metricsAt([], .5), { TP: 0, FP: 0, TN: 0, FN: 0, accuracy: null, precision: null, recall: null, fpr: null });
assert.equal(auc([]), null);
assert.equal(auc([{ actual: 1, score: .5 }]), null);
assert.equal(auc([{ actual: 1, score: .5 }, { actual: 0, score: .5 }]), .5);
assert.equal(auc([{ actual: 1, score: .9 }, { actual: 0, score: .1 }]), 1);
assert.equal(auc([{ actual: 1, score: .1 }, { actual: 0, score: .9 }]), 0);
assert.equal(auc(scores.map(r => ({ ...r, score: r.score * 7 + 13 }))), result.classification.auc);
const exactBoundary = metricsAt([{ actual: 1, score: .5 }, { actual: 0, score: .5 }], .5);
assert.equal(exactBoundary.TP, 1);
assert.equal(exactBoundary.FP, 1, 'threshold equality predicts bad');
for (const threshold of [0, .2, .5, 1]) {
  const m = metricsAt(scores, threshold), audit = auditAt(scores, threshold);
  assert.equal(m.TP + m.FP + m.TN + m.FN, 200);
  assert.equal(audit.groups.reduce((s, g) => s + g.count, 0), 200);
  assert.equal(audit.groups.reduce((s, g) => s + g.fprDenominator, 0), 140);
}
assert.equal(auditAt([{ score: .8, actual: 1, age: 20 }], .5).groups[0].fpr, null);
assert.equal(auditAt([], .5).fprGap, null);
assert.throws(() => metricsAt(scores, NaN));
assert.throws(() => auc([{ actual: 2, score: .2 }]));
assert.throws(() => analyzeFinance([]));
assert.throws(() => analyzeFinance(records.map((r, i) => i ? r : { ...r, amount: null })));
assert.throws(() => analyzeFinance(records.map((r, i) => i ? r : { ...r, sourceRow: records[1].sourceRow })));
const model = fitLogistic(train);
const alteredTest = test.map(r => ({ ...r, amount: 1e9, duration: 9999, installmentRate: 999, existingCredits: 99 }));
const combined = [...train, ...alteredTest];
// Refit using the fixed membership: changing held-out values cannot affect fit or normalization.
const trainOnlyRefit = fitLogistic(combined.filter(r => result.split.trainRows.includes(r.sourceRow)));
assert.deepEqual(trainOnlyRefit.weights, model.weights);
assert.deepEqual(trainOnlyRefit.normalization, model.normalization);
const testIds = new Set(result.split.testRows);
const changedHoldout = analyzeFinance(records.map(r => testIds.has(r.sourceRow) ? { ...r, amount: r.amount * 10, duration: r.duration * 3 } : r));
assert.deepEqual(changedHoldout.classification.weights, result.classification.weights);
assert.deepEqual(changedHoldout.classification.normalization, result.classification.normalization);
assert.deepEqual(changedHoldout.regression.coefficients, result.regression.coefficients);
assert.deepEqual(changedHoldout.regression.normalization, result.regression.normalization);
assert.ok(model.predict(alteredTest[0]) !== model.predict(test[0]));
assert.equal(model.predict({ ...test[0], age: 999 }), model.predict(test[0]), 'age is audit-only');
const regression = fitRegression(train);
assert.equal(regression.predict({ ...test[0], amount: 1e9 }), regression.predict(test[0]), 'amount target never enters prediction');
assert.deepEqual(fitRegression(combined.filter(r => result.split.trainRows.includes(r.sourceRow))).coefficients, regression.coefficients);
assert.ok(result.regression.mae < result.regression.baselineMae);
assert.ok(result.classification.trainLogLoss < result.classification.baselineLogLoss);
assert.ok(result.clustering.converged);
assert.ok(result.clustering.iterations > 1 && result.clustering.iterations < 100);
assert.equal(result.clustering.centroids.length, 3);
assert.equal(result.clustering.centroids.reduce((s, c) => s + c.count, 0), 1000);
assert.ok(result.clustering.history.every((v, i, h) => !i || v <= h[i - 1] + 1e-8));
const constant = records.slice(0, 10).map(r => ({ ...r, amount: 10, duration: 6 }));
assert.ok(kmeans(constant).converged, 'constant input must not produce division by zero');
assert.throws(() => kmeans(records, 0));
assert.throws(() => kmeans(records, 3, 2026, 0));
const constantRegression = fitRegression(constant);
assert.ok(Number.isFinite(constantRegression.predict(constant[0])));
function finiteTree(value) {
  if (typeof value === 'number') assert.ok(Number.isFinite(value));
  else if (value && typeof value === 'object') Object.values(value).forEach(finiteTree);
}
finiteTree(result);
const roc = result.classification.roc;
const trapezoid = roc.slice(1).reduce((s, b, i) => s + (b.fpr - roc[i].fpr) * (b.recall + roc[i].recall) / 2, 0);
assert.ok(Math.abs(trapezoid - result.classification.auc) < 1e-12);
const python = spawnSync('python3', ['aifn-labs.py'], { cwd: 'public/aifn', encoding: 'utf8', timeout: 120000 });
assert.equal(python.status, 0, python.error?.message ?? python.stderr);
const cross = JSON.parse(python.stdout.split('\n').find(line => line.startsWith('CROSS_LANGUAGE ')).slice('CROSS_LANGUAGE '.length));
for (const [key, expected] of Object.entries({ auc: result.classification.auc, mae: result.regression.mae, baselineMae: result.regression.baselineMae, firstScore: scores[0].score, inertia: result.clustering.inertia, clusterIterations: result.clustering.iterations })) assert.ok(Math.abs(cross[key] - expected) < 1e-7, `Python/JS ${key}`);
cross.weights.forEach((v, j) => assert.ok(Math.abs(v - result.classification.weights[j]) < 1e-12));
console.log(JSON.stringify({ status: 'PASS', runtimeMs, records: 1000, split: [800, 200], auc: result.classification.auc, mae: result.regression.mae, baselineMae: result.regression.baselineMae, iterations: result.clustering.iterations, inertia: result.clustering.inertia, checks: ['threshold boundaries', 'zero denominators', 'AUC ties and monotonic invariance', 'train-only normalization', 'no target/age leakage', 'deterministic stratification', 'train loss beats baseline', 'regression holdout beats baseline', 'finite outputs', 'k-means convergence', 'full offline Python cross-language parity'] }));
